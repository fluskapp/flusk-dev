/**
 * Emits src/ui/react/tokens.css from the same generator the legacy bundle
 * uses (styles-tokens.ts / styles-theme.ts via the tsc build), so every value
 * in the React app still traces to the IntelliJ theme dumps in
 * docs/expUI_*.json — the traceability comment on each token survives.
 *
 * Runs after `tsc -p tsconfig.build.json` (the npm scripts sequence it).
 * The output is generated, gitignored, and exempt from the design gate.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { THEME_CSS } from "../dist/ui/styles-theme.js";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "src", "ui", "react", "tokens.css");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
	out,
	`/* GENERATED by scripts/gen-tokens.mjs — edit src/ui/styles-tokens.ts instead. */\n${THEME_CSS}\n`,
);
process.stdout.write(`tokens: wrote ${out}\n`);
